import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { expect, test } from '@playwright/test'
import { clearAndSeedWorkspace, launchApp, seededWorkspaceId } from './workspace-canvas.helpers'
import type { SeedNode } from './workspace-canvas.helpers'
import {
  installPtySessionCapture,
  resolveFirstAgentSessionId,
  writeToPty,
} from './workspace-canvas.agent-status-watcher.helpers'
import type { AgentRunSnapshot } from '../../src/shared/contracts/dto/agentRunState'

// Eclipse Code: an agent asks the user with a card next to its window; one click answers it and
// the answer reaches the agent. Each agent's task list shows as a to-do card.

const QUESTION = {
  question: 'Onde o botão "Entrar com Google" aparece?',
  context: 'A tela de login tem e-mail e senha.',
  options: [
    { label: 'Acima do e-mail', detail: 'Mais usado em lojas; 1 arquivo.', recommended: true },
    { label: 'Abaixo do botão Entrar', detail: 'Mesmo custo.' },
  ],
}

function questionCard(id: string, overrides: Record<string, unknown>): SeedNode {
  return {
    id,
    title: 'Líder',
    kind: 'question' as SeedNode['kind'],
    position: { x: 120 + Number(id.length) * 10, y: 120 },
    width: 360,
    height: 420,
    status: null,
    task: {
      ...QUESTION,
      allowOther: true,
      askedByNodeId: 'lead-gone',
      status: 'pending',
      answer: null,
      answeredAt: null,
      createdAt: new Date().toISOString(),
      ...overrides,
    } as unknown as SeedNode['task'],
  }
}

function todosCard(id: string, ownerNodeId: string, x: number): SeedNode {
  return {
    id,
    title: 'Dev 1',
    kind: 'todos' as SeedNode['kind'],
    position: { x, y: 600 },
    width: 360,
    height: 320,
    status: null,
    task: {
      ownerNodeId,
      items: [
        { text: 'Ler a rota', status: 'completed' },
        { text: 'Criar a rota', status: 'in_progress' },
      ],
      updatedAt: null,
    } as unknown as SeedNode['task'],
  }
}

test.describe('Workspace Canvas - question and to-do cards', () => {
  test('the agent asks with a card and one click delivers the answer', async () => {
    const root = await mkdtemp(join(tmpdir(), 'eclipse-code-cards-'))
    const record = join(root, 'records.jsonl')
    const { electronApp, window } = await launchApp({
      windowMode: 'inactive',
      env: {
        CLAUDE_CONFIG_DIR: join(root, 'claude'),
        CODEX_HOME: join(root, 'codex'),
        ECLIPSE_CODE_TEST_AGENT_SESSION_SCENARIO: 'claude-prompt-strict',
        ECLIPSE_CODE_TEST_CLAUDE_HOOK_INSTALL_FAILURE: '0',
        ECLIPSE_CODE_TEST_USE_REAL_AGENTS: '0',
        ECLIPSE_CODE_TEST_PROMPT_RECORD: record,
        ECLIPSE_CODE_TEST_PROMPT_DIALOG: join(root, 'dialog'),
      },
    })
    try {
      await clearAndSeedWorkspace(
        window,
        [
          {
            id: 'cards-task',
            title: 'Login com Google',
            kind: 'task',
            status: null,
            position: { x: 100, y: 100 },
            width: 460,
            height: 280,
            task: {
              requirement: 'Login com Google',
              status: 'todo',
              linkedAgentNodeId: null,
              lastRunAt: null,
              autoGeneratedTitle: false,
            },
          },
        ],
        {
          settings: {
            defaultProvider: 'claude-code',
            customModelEnabledByProvider: { 'claude-code': false },
          },
        },
      )
      await installPtySessionCapture(window)
      await window.locator('[data-testid="task-node-run-agent"]').click()
      const agent = window.locator('.terminal-node').first()
      await expect(agent).toContainText('STRICT_READY')
      await expect.poll(() => resolveFirstAgentSessionId(window)).not.toBeNull()
      const sessionId = (await resolveFirstAgentSessionId(window))!
      await writeToPty(window, { sessionId, data: 'manual baseline\r' })
      await expect(agent).toContainText('STRICT_TURN_1')
      const snapshot = () =>
        window.evaluate(
          id =>
            window.eclipseCodeApi.controlSurface.invoke<AgentRunSnapshot>({
              kind: 'query',
              id: 'agent.get',
              payload: { sessionId: id },
            }),
          sessionId,
        )
      await expect.poll(async () => (await snapshot()).state).toBe('idle')
      const agentNodeId = (await snapshot()).nodeId!

      const invoke = (id: string, payload: unknown) =>
        window.evaluate(
          ({ id: operationId, payload: input }) =>
            window.eclipseCodeApi.controlSurface.invoke<Record<string, unknown>>({
              kind: operationId === 'question.history' ? 'query' : 'command',
              id: operationId,
              payload: input,
            }),
          { id, payload },
        )

      const created = (await invoke('question.create', {
        ...QUESTION,
        askedByNodeId: agentNodeId,
      })) as { nodeId: string }
      const card = window.getByTestId('question-node')
      await expect(card).toHaveAttribute('data-question-status', 'pending')
      await expect(card).toContainText(QUESTION.question)
      await expect(card).toContainText('Recommended')
      await expect(
        window.getByTestId(`workspace-attention-question-${seededWorkspaceId}-${created.nodeId}`),
      ).toBeVisible()

      await invoke('todos.sync', {
        ownerNodeId: agentNodeId,
        items: [
          { text: 'Ler a rota', status: 'completed' },
          { text: 'Criar a rota', status: 'in_progress' },
          { text: 'Testes', status: 'pending' },
        ],
      })
      const todos = window.getByTestId('todos-node')
      await expect(todos.getByTestId('todos-node-progress')).toHaveText('1 of 3 done')
      await expect(todos.getByTestId('todos-node-item')).toHaveCount(3)

      if (process.env['CARDS_SHOT']) {
        await invoke('canvas.focus', { target: { kind: 'node', nodeId: created.nodeId } })
        await window.waitForTimeout(800)
        await window.screenshot({ path: process.env['CARDS_SHOT'] })
      }

      await card.getByTestId('question-node-option-0').click()
      // Answered: the card leaves the canvas right away.
      await expect(window.getByTestId('question-node')).toHaveCount(0)
      await expect
        .poll(async () => await readFile(record, 'utf8').catch(() => ''))
        .toContain('Acima do e-mail')
      expect(await readFile(record, 'utf8')).toContain('[pergunta respondida]')
      await expect(
        window.getByTestId(`workspace-attention-question-${seededWorkspaceId}-${created.nodeId}`),
      ).toHaveCount(0)

      const history = (await invoke('question.history', { projectId: seededWorkspaceId })) as {
        decisions: Array<{ question: string; answer: string }>
      }
      expect(history.decisions).toEqual([
        expect.objectContaining({ question: QUESTION.question, answer: 'Acima do e-mail' }),
      ])
      if (process.env['CARDS_SHOT_ANSWERED']) {
        await window.screenshot({ path: process.env['CARDS_SHOT_ANSWERED'] })
      }

      // Several questions in one card: answer each, skip one, send once.
      await expect.poll(async () => (await snapshot()).state).toBe('idle')
      const many = (await invoke('question.create', {
        questions: [
          {
            header: 'Banco',
            question: 'Qual banco guarda as sessões?',
            options: [{ label: 'Redis' }, { label: 'Postgres' }],
          },
          {
            header: 'Telas',
            question: 'Quais telas mudam?',
            multiSelect: true,
            options: [{ label: 'Login' }, { label: 'Cadastro' }],
          },
          { header: 'Prazo', question: 'Sobe hoje?', options: [{ label: 'Sim' }] },
        ],
        askedByNodeId: agentNodeId,
      })) as { nodeId: string }
      const manyCard = window.locator('[data-testid="question-node"][data-question-count="3"]')
      await expect(manyCard).toHaveAttribute('data-question-status', 'pending')
      if (process.env['CARDS_SHOT_MANY']) {
        await invoke('canvas.focus', { target: { kind: 'node', nodeId: many.nodeId } })
        await window.waitForTimeout(800)
        await window.screenshot({ path: process.env['CARDS_SHOT_MANY'] })
      }
      const sendAll = manyCard.getByTestId('question-node-send-all')
      await expect(sendAll).toBeDisabled()
      await manyCard.getByTestId('question-node-option-0').click()
      await manyCard.getByTestId('question-node-option-0').click()
      await manyCard.getByTestId('question-node-option-1').click()
      await manyCard.getByTestId('question-node-tab-2').click()
      await manyCard.getByTestId('question-node-skip').click()
      await sendAll.click()
      await expect(manyCard).toHaveCount(0)
      await expect
        .poll(async () => await readFile(record, 'utf8').catch(() => ''))
        .toContain('[perguntas respondidas] 3 perguntas')
      const recorded = await readFile(record, 'utf8')
      expect(recorded).toContain('Qual banco guarda as sessões? -> Redis')
      expect(recorded).toContain('Quais telas mudam? -> Login, Cadastro')
      expect(recorded).toContain('Sobe hoje? -> pulada')
    } finally {
      await electronApp.close()
      await rm(root, { recursive: true, force: true })
    }
  })

  test('a long title never pushes the close button out of the window', async () => {
    const { electronApp, window } = await launchApp({ windowMode: 'inactive' })
    const longTitle = 'claude · Líder da tarefa de login com Google e cadastro com e-mail '.repeat(
      3,
    )
    try {
      await clearAndSeedWorkspace(window, [
        { ...questionCard('long', {}), title: longTitle, width: 300 },
        {
          id: 'long-task',
          title: longTitle,
          kind: 'task',
          status: null,
          position: { x: 600, y: 120 },
          width: 300,
          height: 260,
          task: {
            requirement: longTitle,
            status: 'todo',
            linkedAgentNodeId: null,
            lastRunAt: null,
            autoGeneratedTitle: false,
          },
        },
      ])
      for (const selector of [
        '[data-testid="question-node"]',
        '[data-cove-part="window"]:has([data-testid="task-node-run-agent"])',
      ]) {
        const windowNode = window.locator(selector).first()
        await expect(windowNode).toBeVisible()
        const close = windowNode.locator('.cove-window-header__trailing').last()
        await expect(close).toBeVisible()
        const frame = (await windowNode.boundingBox())!
        const controls = (await close.boundingBox())!
        expect(controls.x + controls.width).toBeLessThanOrEqual(frame.x + frame.width + 1)
      }
      if (process.env['CARDS_SHOT_LONG']) {
        await window.screenshot({ path: process.env['CARDS_SHOT_LONG'] })
      }
    } finally {
      await electronApp.close()
    }
  })

  test('answered cards leave the canvas; pending cards survive a restart', async () => {
    const userDataDir = await mkdtemp(join(tmpdir(), 'eclipse-code-cards-restart-'))
    const first = await launchApp({ userDataDir, cleanupUserDataDir: false })
    try {
      await clearAndSeedWorkspace(first.window, [
        questionCard('pending', {}),
        questionCard('answered-long-ago', {
          status: 'answered',
          answer: { optionIndex: 0, text: '' },
          answeredAt: new Date(Date.now() - 2 * 60_000).toISOString(),
        }),
        todosCard('todos-kept', 'pending', 600),
        todosCard('todos-orphan', 'agent-that-closed', 1000),
      ])
      const cards = first.window.getByTestId('question-node')
      await expect(cards).toHaveCount(1)
      await expect(cards).toHaveAttribute('data-question-status', 'pending')
      await expect(first.window.getByTestId('todos-node')).toHaveCount(1)
    } finally {
      await first.electronApp.close()
    }

    const second = await launchApp({ userDataDir, cleanupUserDataDir: true })
    try {
      const card = second.window.getByTestId('question-node')
      await expect(card).toHaveCount(1)
      await expect(card).toContainText(QUESTION.question)
      await expect(card).toHaveAttribute('data-question-status', 'pending')
      await expect(second.window.getByTestId('todos-node-progress')).toHaveText('1 of 2 done')
    } finally {
      await second.electronApp.close()
    }
  })
})
